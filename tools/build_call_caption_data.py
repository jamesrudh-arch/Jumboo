#!/usr/bin/env python3
"""Generate optional caption timing from the approved first-call dialogue."""
import hashlib
import json
import re
import wave
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
AUDIO = ROOT / 'brand/intro/call_audio'
GAME_AUDIO = ROOT / 'game/assets/intro/first_call_preview.wav'
timing = json.loads((AUDIO / 'dialogue_timeline.json').read_text())
readme = (AUDIO / 'README.md').read_text()
lines = re.findall(r'^\*\*(Marcus|Brother):\*\* (.+)$', readme, flags=re.MULTILINE)
events = timing['events']
if len(lines) != len(events):
    raise ValueError('Approved dialogue and timing contain different line counts')
with wave.open(str(GAME_AUDIO), 'rb') as w:
    if (w.getnchannels(), w.getsampwidth(), w.getframerate()) != (1, 2, timing['sample_rate_hz']):
        raise ValueError('Unexpected game dialogue format')
    pcm = w.readframes(w.getnframes())
if hashlib.sha256(pcm).hexdigest() != timing['mix_pcm_sha256']:
    raise ValueError('Game audio does not match the approved timing')
result = ['# Generated by tools/build_call_caption_data.py from the approved dialogue.',
          '# Whole-line cues; no word-level timing or localization is implied.',
          'extends RefCounted', '', f"const SAMPLE_RATE := {timing['sample_rate_hz']}", 'const CUES := [']
for (speaker, text), event in zip(lines, events):
    if speaker.lower() != event['speaker']:
        raise ValueError(f'Speaker mismatch for {event["file"]}')
    result.append(f'\t{{"start": {event["start_sample"]}, "end": {event["end_sample"]}, "text": {json.dumps(speaker.upper() + ": " + text, ensure_ascii=False)}}},')
result += [']', '', 'static func text_at_sample(sample: int) -> String:',
           '\tfor cue in CUES:', '\t\tif sample >= cue.start and sample < cue.end:',
           '\t\t\treturn cue.text', '\treturn ""', '']
out = ROOT / 'game/call_caption_data.gd'
out.write_text('\n'.join(result), encoding='utf-8')
print(f'Wrote {out} with {len(lines)} sample-bounded cues')
